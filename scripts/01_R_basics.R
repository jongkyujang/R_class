# 7. 비교 연산: 조건이 맞는지 확인하기
# ============================================================

5 > 3
5 < 3
5 >= 5
5 <= 3

5 == 5    # 같은가?
5 != 5    # 다른가?

# "<-"는 저장, "=="는 비교입니다.
x <- 10
x == 10

# 벡터에서는 각 값에 조건을 적용합니다.
ages <- c(25, 40, 35, 60, 50)

ages >= 40

# TRUE인 위치의 값만 선택합니다.
ages[ages >= 40]

# 같은 위치에 대응하는 환자 ID도 선택할 수 있습니다.
patient_ids[ages >= 40]


# ============================================================
# 8. 논리 연산: 여러 조건 조합하기
# ============================================================
# & : 두 조건을 모두 만족
# | : 두 조건 중 하나 이상 만족
# ! : TRUE와 FALSE를 반대로 바꾸기

# 30세 이상이면서 50세 미만
(ages >= 30) & (ages < 50)

ages[(ages >= 30) & (ages < 50)]

# 30세 미만이거나 50세 이상
ages[(ages < 30) | (ages >= 50)]

# 40세 이상이 아닌 값
ages[!(ages >= 40)]

# %in%: 지정한 값들 중 하나에 해당하는지 확인
patient_ids %in% c("P01", "P03")

# 논리값을 합하면 TRUE의 개수를 셀 수 있습니다.
sum(ages >= 40)


# ============================================================
# 9. 결측값: 관측되지 않은 값
# ============================================================
# NA는 값이 없거나 알 수 없음을 나타냅니다.
# 숫자 0과는 다릅니다.

expression_na <- c(10, 20, NA, 40, 100)

mean(expression_na)

# is.na(): 어떤 위치가 결측값인지 확인
is.na(expression_na)

# na.rm = TRUE: 결측값을 제외하고 계산
mean(expression_na, na.rm = TRUE)

# 결측값 개수
sum(is.na(expression_na))

# 결측값이 아닌 값만 선택
expression_na[!is.na(expression_na)]


# ============================================================
# 10. 조건문: 조건에 따라 다른 작업 실행하기
# ============================================================
# if에는 TRUE/FALSE 하나로 판단할 수 있는 조건을 넣습니다.

patient_age <- 65

if (patient_age >= 60) {
  print("60세 이상")
} else {
  print("60세 미만")
}

# 여러 값 각각에 조건을 적용하려면 ifelse()를 사용할 수 있습니다.
age_group <- ifelse(ages >= 40, "40세 이상", "40세 미만")

age_group


