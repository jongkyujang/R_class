# ============================================================
# 6. 함수: 이름을 이용해 정해진 작업 수행하기
# ============================================================
# 함수이름(입력값) 형태로 사용합니다.

expression <- c(10, 20, 30, 40, 100)

sum(expression)       # 합계
mean(expression)      # 평균
