sd(expression)        # 표본 표준편차
summary(expression)   # 요약 통계

# 함수의 옵션을 인자(argument)라고 합니다.
# 아래에서는 digits 인자로 반올림할 소수 자릿수를 지정합니다.
mean_value <- mean(expression)

round(mean_value, digits = 2)

